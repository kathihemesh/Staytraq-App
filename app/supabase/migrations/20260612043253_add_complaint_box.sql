-- SQL migration to support Complaint Box feature

BEGIN;

-- 1. Add complaint_token to pg_owners table
ALTER TABLE public.pg_owners ADD COLUMN IF NOT EXISTS complaint_token text UNIQUE;
ALTER TABLE public.pg_owners ALTER COLUMN complaint_token SET DEFAULT substring(gen_random_uuid()::text from 1 for 12);

-- Update existing owners to have a unique token if null
UPDATE public.pg_owners
SET complaint_token = substring(gen_random_uuid()::text from 1 for 12)
WHERE complaint_token IS NULL;

-- Make complaint_token NOT NULL
ALTER TABLE public.pg_owners ALTER COLUMN complaint_token SET NOT NULL;

-- 2. Create complaints table
CREATE TABLE IF NOT EXISTS public.complaints (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid NOT NULL REFERENCES public.pg_owners(id) ON DELETE CASCADE,
  tenant_phone text NOT NULL,
  complaint_message text NOT NULL,
  status text NOT NULL DEFAULT 'Under Working' CHECK (status IN ('Under Working', 'Resolved', 'Ignored')),
  owner_response text,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Enable RLS
ALTER TABLE public.complaints ENABLE ROW LEVEL SECURITY;

-- 4. Create RLS policies
DROP POLICY IF EXISTS "owners_select_own_complaints" ON public.complaints;
CREATE POLICY "owners_select_own_complaints" ON public.complaints
  FOR SELECT TO authenticated USING (owner_id = auth.uid());

DROP POLICY IF EXISTS "owners_insert_own_complaints" ON public.complaints;
CREATE POLICY "owners_insert_own_complaints" ON public.complaints
  FOR INSERT TO authenticated WITH CHECK (owner_id = auth.uid());

DROP POLICY IF EXISTS "owners_update_own_complaints" ON public.complaints;
CREATE POLICY "owners_update_own_complaints" ON public.complaints
  FOR UPDATE TO authenticated USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());

DROP POLICY IF EXISTS "owners_delete_own_complaints" ON public.complaints;
CREATE POLICY "owners_delete_own_complaints" ON public.complaints
  FOR DELETE TO authenticated USING (owner_id = auth.uid());

-- Ensure RLS is enabled on pg_owners and policies exist
ALTER TABLE public.pg_owners ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "pg_owners_select_own" ON public.pg_owners;
CREATE POLICY "pg_owners_select_own" ON public.pg_owners
  FOR SELECT TO authenticated USING (id = auth.uid());

DROP POLICY IF EXISTS "pg_owners_update_own" ON public.pg_owners;
CREATE POLICY "pg_owners_update_own" ON public.pg_owners
  FOR UPDATE TO authenticated USING (id = auth.uid()) WITH CHECK (id = auth.uid());

-- 5. Grant permissions
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.complaints TO authenticated;
GRANT SELECT, UPDATE ON TABLE public.pg_owners TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

COMMIT;;
