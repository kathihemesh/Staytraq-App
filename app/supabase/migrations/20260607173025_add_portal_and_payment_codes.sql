-- 1. Create monthly_payment_links table
CREATE TABLE IF NOT EXISTS public.monthly_payment_links (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid NOT NULL REFERENCES public.pg_owners(id) ON DELETE CASCADE,
  month integer NOT NULL CHECK (month >= 1 AND month <= 12),
  year integer NOT NULL,
  portal_token text UNIQUE NOT NULL DEFAULT substring(gen_random_uuid()::text from 1 for 12),
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
  UNIQUE (owner_id, month, year)
);

-- 2. Modify tenants_table to support unique payment codes
ALTER TABLE public.tenants_table ADD COLUMN IF NOT EXISTS payment_code text UNIQUE;
ALTER TABLE public.tenants_table ALTER COLUMN payment_code SET DEFAULT ('ST-' || upper(substring(gen_random_uuid()::text from 1 for 6)));

-- Update existing tenants to populate payment_code
UPDATE public.tenants_table 
SET payment_code = ('ST-' || upper(substring(gen_random_uuid()::text from 1 for 6))) 
WHERE payment_code IS NULL;

-- Make payment_code NOT NULL for future safety
ALTER TABLE public.tenants_table ALTER COLUMN payment_code SET NOT NULL;

-- 3. Add unique index for non-null utr_number to prevent duplicate submissions
CREATE UNIQUE INDEX IF NOT EXISTS payments_utr_number_unique_idx ON public.payments (utr_number) WHERE utr_number IS NOT NULL;;
