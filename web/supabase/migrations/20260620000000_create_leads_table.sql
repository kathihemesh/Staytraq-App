-- Create leads table
CREATE TABLE public.leads (
    id bigint generated by default as identity primary key,
    owner_id uuid references public.pg_owners(id) on delete cascade not null,
    name text not null,
    phone text not null,
    room_type text,
    sharing_preference text,
    move_in_date date,
    room_no text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable RLS
ALTER TABLE public.leads ENABLE ROW LEVEL SECURITY;

-- Create RLS policies
CREATE POLICY "Owners can view and manage their own leads"
    ON public.leads
    FOR ALL
    TO authenticated
    USING (auth.uid() = owner_id)
    WITH CHECK (auth.uid() = owner_id);
