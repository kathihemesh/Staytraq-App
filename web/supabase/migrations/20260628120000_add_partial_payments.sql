-- Partial payments: track cumulative received amount + per-submission proof history.

-- 1. amount_paid column (cumulative approved amount).
ALTER TABLE public.payments
  ADD COLUMN IF NOT EXISTS amount_paid numeric NOT NULL DEFAULT 0;

-- Backfill: fully-paid records have amount_paid = total_amount.
UPDATE public.payments SET amount_paid = total_amount WHERE status = 'paid';

-- 2. Allow the new 'partially_paid' status.
ALTER TABLE public.payments DROP CONSTRAINT IF EXISTS payments_status_check;
ALTER TABLE public.payments
  ADD CONSTRAINT payments_status_check
  CHECK (status = ANY (ARRAY['pending'::text, 'late'::text, 'submitted'::text, 'paid'::text, 'rejected'::text, 'partially_paid'::text]));

-- 3. Per-submission proof history (each tenant proof kept, so partial screenshots aren't lost).
CREATE TABLE IF NOT EXISTS public.payment_submissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id bigint NOT NULL REFERENCES public.payments(id) ON DELETE CASCADE,
  owner_id uuid NOT NULL REFERENCES public.pg_owners(id) ON DELETE CASCADE,
  tenant_id bigint REFERENCES public.tenants_table(id) ON DELETE SET NULL,
  amount_approved numeric,
  screenshot_path text,
  utr_number text,
  payment_method text DEFAULT 'upi',
  status text NOT NULL DEFAULT 'submitted' CHECK (status = ANY (ARRAY['submitted'::text, 'approved'::text, 'rejected'::text])),
  notes text,
  submitted_at timestamptz DEFAULT now(),
  verified_at timestamptz,
  created_at timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS payment_submissions_payment_id_idx ON public.payment_submissions(payment_id);
CREATE INDEX IF NOT EXISTS payment_submissions_owner_id_idx ON public.payment_submissions(owner_id);

-- 4. RLS: owner can see/manage their own submissions. Public tenant submissions
-- are inserted by the server (service role) which bypasses RLS.
ALTER TABLE public.payment_submissions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS payment_submissions_select_own ON public.payment_submissions;
CREATE POLICY payment_submissions_select_own ON public.payment_submissions
  FOR SELECT TO authenticated USING (owner_id = auth.uid());

DROP POLICY IF EXISTS payment_submissions_insert_own ON public.payment_submissions;
CREATE POLICY payment_submissions_insert_own ON public.payment_submissions
  FOR INSERT TO authenticated WITH CHECK (owner_id = auth.uid());

DROP POLICY IF EXISTS payment_submissions_update_own ON public.payment_submissions;
CREATE POLICY payment_submissions_update_own ON public.payment_submissions
  FOR UPDATE TO authenticated USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());

DROP POLICY IF EXISTS payment_submissions_delete_own ON public.payment_submissions;
CREATE POLICY payment_submissions_delete_own ON public.payment_submissions
  FOR DELETE TO authenticated USING (owner_id = auth.uid());

-- 5. Backfill submission history from existing payments that already have a proof.
INSERT INTO public.payment_submissions (payment_id, owner_id, tenant_id, screenshot_path, utr_number, payment_method, status, amount_approved, submitted_at, verified_at)
SELECT p.id, p.owner_id, p.tenant_id, p.screenshot_path, p.utr_number, p.payment_method,
       CASE WHEN p.status = 'paid' THEN 'approved' ELSE 'submitted' END,
       CASE WHEN p.status = 'paid' THEN p.total_amount ELSE NULL END,
       COALESCE(p.submitted_at, p.created_at, now()), p.verified_at
FROM public.payments p
WHERE p.screenshot_path IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM public.payment_submissions ps WHERE ps.payment_id = p.id);
